"""Pick the deployed models (on VALIDATION macro-F1) and write the comparison, slices, robustness test and summary.

    python ml/report.py [--no-robustness]

Writes models/deployed.json, results/report.json, results/dataset.json, results/SUMMARY.md and the figures
model_comparison / by_kind / lab_vs_field / robustness / selective_prediction / dataset_crops (.png).
"""
import io
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch
from PIL import Image, ImageEnhance, ImageFilter
from sklearn.metrics import precision_recall_fscore_support
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from train import MODELS, RESULTS, ROOT, build, eval_tensor  # noqa: E402
import vision  # noqa: E402

GREEN = "#2e7d32"


def noise(im, i):
    a = np.asarray(im, np.float32) + np.random.default_rng(i).normal(0, 20, np.asarray(im).shape)
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))


def jpeg(im, i):
    b = io.BytesIO(); im.save(b, "JPEG", quality=15); return Image.open(b).convert("RGB")


def occlude(im, i):
    r = np.random.default_rng(i); w, h = im.size; s = int(0.5 * min(w, h))  # 25% of a square image
    x, y = r.integers(0, w - s + 1), r.integers(0, h - s + 1)
    im = im.copy(); im.paste((128, 128, 128), (x, y, x + s, y + s)); return im


# Same simulated lab-to-field corruptions as v1 (deterministic per image index).
CONDITIONS = {
    "Clean": lambda im, i: im,
    "Defocus blur": lambda im, i: im.filter(ImageFilter.GaussianBlur(2.5)),
    "Sensor noise": noise,
    "Low light": lambda im, i: ImageEnhance.Brightness(im).enhance(0.45),
    "Over-exposure": lambda im, i: ImageEnhance.Brightness(im).enhance(1.6),
    "JPEG compression": jpeg,
    "25% occlusion": occlude,
}


def stressed(i, path, cond):
    """Corrupt one test image; return (model input, passes the photo-quality gate)."""
    im = CONDITIONS[cond](Image.open(ROOT / path).convert("RGB"), i)
    hard = [c for c in vision.quality_check(np.asarray(im))["checks"] if not c["passed"] and c["severity"] == "hard"]
    return eval_tensor(torch.from_numpy(np.asarray(im)).permute(2, 0, 1)), not hard


def f1(y, p):
    return float(precision_recall_fscore_support(y, p, average="macro", zero_division=0)[2])


def table(md, head, rows):
    md += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows] + [""]


def main():
    md = ["# AgroVision v2 results (auto-generated by ml/report.py)\n"]
    rep, deployed = {}, {}
    all_m = {t: {d.parent.name: json.loads(d.read_text()) for d in sorted((RESULTS / t).glob("*/metrics.json"))} for t in ("leaf", "pest")}
    for task, ms in all_m.items():                          # deployed model = best VALIDATION macro-F1 (never test)
        val = {a: torch.load(MODELS / f"{task}_{a}.pt", map_location="cpu", weights_only=False)["val_f1"] for a in ms}
        if val:
            deployed[task] = max(val, key=val.get)
            rep[f"{task}_val_f1"] = val
    (MODELS / "deployed.json").write_text(json.dumps(deployed))
    print("deployed:", deployed, flush=True)

    # --- dataset
    leaf = pd.read_csv(ROOT / "data" / "manifest_leaf.csv")
    pest = pd.read_csv(ROOT / "data" / "manifest_pest.csv")
    real = leaf[leaf.kind != "other"]
    ds = {"leaf_images": len(leaf), "leaf_classes": int(leaf.key.nunique()), "crops": int(real.crop.nunique()),
          "pest_images": len(pest), "pest_species": int(pest.key.nunique()), "sources": int(leaf.source.nunique()),
          "split": leaf.split.value_counts().to_dict(), "pest_split": pest.split.value_counts().to_dict(),
          "by_kind": {k: {"classes": int(g.key.nunique()), "images": len(g)} for k, g in leaf.groupby("kind")},
          "by_imagery": leaf.imagery.value_counts().to_dict(),
          "by_crop": {c: {"classes": int(g.key.nunique()), "images": len(g)} for c, g in real.groupby("crop")},
          "split_method": "Stratified by class, grouped by near-duplicate cluster (256-bit dHash, Hamming <= 10, within source+class) and leaf id; seed 42"}
    (RESULTS / "dataset.json").write_text(json.dumps(ds, indent=1))
    crops = sorted(ds["by_crop"], key=lambda c: ds["by_crop"][c]["images"])
    fig, ax = plt.subplots(figsize=(8, 0.23 * len(crops) + 1))
    ax.barh(crops, [ds["by_crop"][c]["images"] for c in crops], color=GREEN)
    ax.set(xlabel="images", title=f"Leaf corpus: {ds['crops']} crops, {ds['leaf_classes']} classes, {len(leaf):,} images")
    fig.tight_layout(); fig.savefig(RESULTS / "dataset_crops.png", dpi=150); plt.close(fig)
    md += ["## Dataset\n", f"Leaf corpus: **{len(leaf):,} images, {ds['leaf_classes']} classes, {ds['crops']} crops**, merged from "
           f"{ds['sources']} public sources; split train/val/test = {ds['split'].get('train')}/{ds['split'].get('val')}/{ds['split'].get('test')}. "
           f"Pest corpus (IP102): **{len(pest):,} images, {ds['pest_species']} species** (official split). {ds['split_method']}.\n"]
    table(md, ["Kind", "Classes", "Images"], [[k, v["classes"], f"{v['images']:,}"] for k, v in ds["by_kind"].items()])

    # --- model comparison (leaf)
    ms = all_m["leaf"]
    if ms:
        keys = [("accuracy", "Accuracy"), ("precision_macro", "Precision"), ("recall_macro", "Recall"), ("f1_macro", "Macro-F1")]
        fig, ax = plt.subplots(figsize=(10, 4.5)); w = 0.8 / len(ms)
        for j, (a, m) in enumerate(ms.items()):
            b = ax.bar(np.arange(len(keys)) + (j - (len(ms) - 1) / 2) * w, [m[k] for k, _ in keys], w, label=m["name"])
            ax.bar_label(b, [f"{m[k]:.3f}" for k, _ in keys], fontsize=7, padding=2, rotation=90)
        ax.set_xticks(range(len(keys)), [l for _, l in keys]); ax.set_ylim(max(0, min(m[k] for m in ms.values() for k, _ in keys) - 0.08), 1.04)
        ax.set_title(f"Leaf model comparison on the held-out test set ({ds['leaf_classes']} classes)"); ax.legend(loc="lower right", fontsize=8)
        fig.tight_layout(); fig.savefig(RESULTS / "model_comparison.png", dpi=150); plt.close(fig)
        md.append("## Leaf-model comparison (held-out test set)\n")
        table(md, ["Model", "Accuracy (95% CI)", "Precision", "Recall", "F1 macro (95% CI)", "Top-3", "ROC-AUC", "Crop acc.", "Lab acc.", "Field acc.",
                   "Params (M)", "CPU p50/p95 (ms)", "Train (min)", "Val F1"],
              [[m["name"] + (" **(deployed)**" if a == deployed["leaf"] else ""),
                f"{m['accuracy']:.4f} ({m['accuracy_ci95'][0]:.4f}-{m['accuracy_ci95'][1]:.4f})", f"{m['precision_macro']:.4f}",
                f"{m['recall_macro']:.4f}", f"{m['f1_macro']:.4f} ({m['f1_macro_ci95'][0]:.4f}-{m['f1_macro_ci95'][1]:.4f})",
                f"{m['top3_accuracy']:.4f}", f"{m['roc_auc_macro_ovr']:.4f}", f"{m['crop_accuracy']:.4f}",
                f"{m['by_imagery'].get('lab', {}).get('accuracy', float('nan')):.4f}", f"{m['by_imagery'].get('field', {}).get('accuracy', float('nan')):.4f}",
                f"{m['params_m']:.1f}", f"{m['latency_ms_cpu']['p50']:.0f}/{m['latency_ms_cpu']['p95']:.0f}", f"{m['train_time_min']:.0f}",
                f"{rep['leaf_val_f1'][a]:.4f}"] for a, m in ms.items()])
        m = ms[deployed["leaf"]]
        # --- slices of the deployed model
        for col, title, fname in (("by_kind", "Results by kind of finding", "by_kind"), ("by_imagery", "Lab vs field photos", "lab_vs_field")):
            sl = {k: v for k, v in m[col].items() if k != "other"}
            fig, ax = plt.subplots(figsize=(7, 3.8)); xs = np.arange(len(sl))
            b1 = ax.bar(xs - 0.2, [v["accuracy"] for v in sl.values()], 0.4, label="accuracy", color=GREEN)
            b2 = ax.bar(xs + 0.2, [v["f1_macro"] for v in sl.values()], 0.4, label="macro-F1", color="#9ccc65")
            ax.bar_label(b1, [f"{v['accuracy']:.3f}" for v in sl.values()], fontsize=8); ax.bar_label(b2, [f"{v['f1_macro']:.3f}" for v in sl.values()], fontsize=8)
            ax.set_xticks(xs, [f"{k}\n(n={v['n']})" for k, v in sl.items()]); ax.set_ylim(0, 1.1); ax.legend(loc="lower right")
            ax.set_title(f"{m['name']} - {title.lower()} (test)"); fig.tight_layout(); fig.savefig(RESULTS / f"{fname}.png", dpi=150); plt.close(fig)
            md.append(f"## {m['name']} - {title} (test)\n")
            table(md, [col[3:].title(), "Test images", "Accuracy", "Precision", "Recall", "F1 macro"],
                  [[k, v["n"], f"{v['accuracy']:.4f}", f"{v['precision_macro']:.4f}", f"{v['recall_macro']:.4f}", f"{v['f1_macro']:.4f}"] for k, v in m[col].items()])
        md.append(f"## {m['name']} - per source (test)\n")
        table(md, ["Source", "Test images", "Accuracy", "F1 macro"], [[k, v["n"], f"{v['accuracy']:.4f}", f"{v['f1_macro']:.4f}"] for k, v in sorted(m["by_source"].items())])
        md.append(f"## {m['name']} - per crop (test)\n")
        table(md, ["Crop", "Test images", "Accuracy", "F1 macro"], [[k, v["n"], f"{v['accuracy']:.4f}", f"{v['f1_macro']:.4f}"] for k, v in sorted(m["by_crop"].items())])
        md.append("Most frequent confusions (true -> predicted): " + "; ".join(f"{c['true']} -> {c['pred']} ({c['n']})" for c in m["top_confusions"][:12]) + "\n")
        worst = sorted(m["per_class"].items(), key=lambda x: x[1]["f1"])[:15]
        md.append("Weakest classes by F1:\n")
        table(md, ["Class", "Precision", "Recall", "F1", "Support"], [[k, f"{v['precision']:.3f}", f"{v['recall']:.3f}", f"{v['f1']:.3f}", v["support"]] for k, v in worst])

        # --- calibrated selective prediction on test
        cal = MODELS / f"leaf_{deployed['leaf']}_calibration.json"
        z = np.load(RESULTS / "leaf" / deployed["leaf"] / "test_probs.npz", allow_pickle=True)
        y, p = z["y"], z["p"].astype(np.float64)
        if cal.exists():
            c = json.loads(cal.read_text())
            p = p ** (1 / c["temperature"]); p /= p.sum(1, keepdims=True)
            rep["calibration"] = {k: c[k] for k in ("temperature", "ece", "ece_calibrated", "val_nll", "val_nll_calibrated", "ood_threshold", "confidence_gate_val")}
            md += [f"## Calibration (validation)\n", f"Temperature {c['temperature']:.2f}; expected calibration error {c['ece']:.4f} -> "
                   f"{c['ece_calibrated']:.4f}; NLL {c['val_nll']:.4f} -> {c['val_nll_calibrated']:.4f}.\n"]
        pred, conf = p.argmax(1), p.max(1)
        rows = [(t, float((conf >= t).mean()), float((pred == y)[conf >= t].mean())) for t in (0.0, 0.5, 0.6, 0.7, 0.8, 0.9, 0.95)]
        rep["selective_test"] = [{"threshold": t, "coverage": c, "accuracy": a} for t, c, a in rows]
        fig, ax = plt.subplots(figsize=(6, 4)); ax.plot([r[1] for r in rows], [r[2] for r in rows], "o-", color=GREEN)
        for t, c, a in rows:
            ax.annotate(f"t={t}", (c, a), textcoords="offset points", xytext=(4, 4), fontsize=8)
        ax.set(xlabel="coverage (fraction answered)", ylabel="accuracy on answered", title="Confidence gate on test: accuracy vs coverage")
        fig.tight_layout(); fig.savefig(RESULTS / "selective_prediction.png", dpi=150); plt.close(fig)
        md.append("## Confidence gate on test (calibrated probability)\n")
        table(md, ["Threshold", "Coverage", "Accuracy on answered"], [[f"{t:.2f}", f"{c:.4f}", f"{a:.4f}"] for t, c, a in rows])

        # --- robustness under simulated field conditions (deployed leaf model, whole test split)
        if "--no-robustness" not in sys.argv:
            ck = torch.load(MODELS / f"leaf_{deployed['leaf']}.pt", map_location="cpu", weights_only=False)
            model = build(deployed["leaf"], len(ck["classes"]), pretrained=False); model.load_state_dict(ck["state_dict"]); model = model.cuda().eval()
            te = leaf[(leaf.split == "test") & (leaf.kind != "other")]
            yt = te["key"].map({c: i for i, c in enumerate(ck["classes"])}).values
            rob = []
            for cond in CONDITIONS:
                ps, gate, paths = [], [], te["path"].values
                with torch.no_grad(), ThreadPoolExecutor(8) as pool:      # threads, not worker processes (Windows)
                    for s0 in range(0, len(paths), 256):
                        items = list(pool.map(lambda i: stressed(i, paths[i], cond), range(s0, min(len(paths), s0 + 256))))
                        with torch.autocast("cuda", dtype=torch.float16):
                            ps.append(model(torch.stack([t for t, _ in items]).cuda()).argmax(1).cpu())
                        gate.append(torch.tensor([g for _, g in items]))
                pp, gg = torch.cat(ps).numpy(), torch.cat(gate).numpy().astype(bool)
                r = {"condition": cond, "accuracy": float((pp == yt).mean()), "f1_macro": f1(yt, pp), "gate_pass_rate": float(gg.mean()),
                     "accuracy_after_gate": float((pp[gg] == yt[gg]).mean()) if gg.any() else None}
                rob.append(r); print(r, flush=True)
            rep["robustness"] = rob
            fig, ax = plt.subplots(figsize=(10, 4.5)); xs = np.arange(len(rob))
            b1 = ax.bar(xs - 0.2, [r["accuracy"] for r in rob], 0.4, label="accuracy", color=GREEN)
            ax.bar(xs + 0.2, [r["f1_macro"] for r in rob], 0.4, label="macro-F1", color="#9ccc65")
            ax.bar_label(b1, [f"{r['accuracy']:.3f}" for r in rob], fontsize=8)
            ax.set_xticks(xs, [r["condition"] for r in rob], rotation=20, ha="right"); ax.set_ylim(0, 1.08); ax.legend(loc="lower left")
            ax.set_title(f"{m['name']} under simulated field conditions (test set)"); fig.tight_layout(); fig.savefig(RESULTS / "robustness.png", dpi=150); plt.close(fig)
        elif (RESULTS / "report.json").exists():
            rep["robustness"] = json.loads((RESULTS / "report.json").read_text()).get("robustness", [])
        if rep.get("robustness"):
            md.append("## Robustness to simulated field conditions (test set)\n")
            table(md, ["Condition", "Accuracy", "Macro-F1", "Quality-gate pass rate", "Accuracy on gate-passed"],
                  [[r["condition"], f"{r['accuracy']:.4f}", f"{r['f1_macro']:.4f}", f"{r['gate_pass_rate']:.2%}",
                    "-" if r["accuracy_after_gate"] is None else f"{r['accuracy_after_gate']:.4f}"] for r in rep["robustness"]])

    # --- pest model
    if all_m["pest"]:
        md.append("## Insect-pest model (IP102, official test split)\n")
        table(md, ["Model", "Accuracy (95% CI)", "Top-3", "Precision", "Recall", "F1 macro", "ROC-AUC", "Val F1"],
              [[m["name"] + (" **(deployed)**" if a == deployed["pest"] else ""), f"{m['accuracy']:.4f} ({m['accuracy_ci95'][0]:.4f}-{m['accuracy_ci95'][1]:.4f})",
                f"{m['top3_accuracy']:.4f}", f"{m['precision_macro']:.4f}", f"{m['recall_macro']:.4f}", f"{m['f1_macro']:.4f}",
                f"{m['roc_auc_macro_ovr']:.4f}", f"{rep['pest_val_f1'][a]:.4f}"] for a, m in all_m["pest"].items()])
    md.append("Figures: results/model_comparison.png, by_kind.png, lab_vs_field.png, robustness.png, selective_prediction.png, dataset_crops.png, "
              "results/leaf/<model>/{training_curves,per_crop_accuracy,per_class_f1_hist}.png\n")
    (RESULTS / "report.json").write_text(json.dumps(rep, indent=1))
    (RESULTS / "SUMMARY.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote", RESULTS / "SUMMARY.md")


if __name__ == "__main__":
    main()
